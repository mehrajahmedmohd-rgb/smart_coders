week = int (input ("enter the number :"))

if week == 1 :
    print("MONDAY")

elif week == 2 :
    print("TUESDAY")

elif week == 3 :
    print("WEDNESDAY")

elif week == 4 :
    print("TURSDAY")

elif week == 5 :
    print("FRIDAY")

elif week == 6 :
    print("SATURDAY")

else:
    print("SUNDAY")